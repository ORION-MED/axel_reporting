def build(out_path: str) -> None:
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = 'Вопросы'

    sheet.append(['Открытые вопросы на 25.08.2026'])
    sheet['A1'].font = Font(bold=True, size=13)
    sheet.append([
        'По строке на вопрос. Решение впишите в жёлтую колонку — так ничего '
        'не потеряется в переписке.'
    ])
    sheet.append([
        'Группы идут по цене: первая держит цифры показателей, последняя — просто '
        'к сведению.'
    ])
    sheet.append([])

    headers = ['№', 'Тема', 'Вопрос', 'Почему это важно', 'Где смотреть',
               'Решение', 'Комментарий']
    sheet.append(headers)
    for column in range(1, len(headers) + 1):
        cell = sheet.cell(sheet.max_row, column)
        cell.font = Font(bold=True)
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(vertical='center', wrap_text=True)
    header_row = sheet.max_row

    number = 0
    for group, items in QUESTIONS:
        sheet.append([group])
        for column in range(1, len(headers) + 1):
            sheet.cell(sheet.max_row, column).fill = GROUP_FILL
        sheet.cell(sheet.max_row, 1).font = Font(bold=True)

        for topic, question, why, where in items:
            number += 1
            sheet.append([number, topic, question, why, where, '', ''])
            for column in (3, 4):
                sheet.cell(sheet.max_row, column).alignment = Alignment(
                    wrap_text=True, vertical='top',
                )
            sheet.cell(sheet.max_row, 6).fill = ANSWER_FILL
            sheet.cell(sheet.max_row, 7).fill = ANSWER_FILL

    for index, width in enumerate([5, 26, 54, 66, 28, 34, 30], start=1):
        sheet.column_dimensions[get_column_letter(index)].width = width
    sheet.freeze_panes = f'A{header_row + 1}'

    workbook.save(out_path)
    print(f'Готово: {out_path}, вопросов {number}')


def main() -> None:
    if len(sys.argv) != 2:
        print(__doc__)
        raise SystemExit(2)
    build(sys.argv[1])


if __name__ == '__main__':
    main()
