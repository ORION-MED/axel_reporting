interface SourcesReferenceTabProps {
    loadedSourceTypes: ReadonlySet<string>
}

/**
 * Компоновка «мастер — деталь»: слева компактный список источников в порядке
 * загрузки, справа подробности выбранного. Прежний вариант выкладывал высокие
 * карточек в столбик — страница прокручивалась на несколько экранов и не давала общей
 * картины, ради которой её и делали.
 */
export function SourcesReferenceTab({ loadedSourceTypes }: SourcesReferenceTabProps) {
    const [selectedSourceType, setSelectedSourceType] = useState(
        REPORTING_SOURCES[0].sourceType,
    )
    // С 07.08.2026 обязательны все девять источников: справочник признаков МО перестал
    // быть необязательным (Н13), и деления на «обязательные / прочие» больше нет.
    const loadedCount = REPORTING_SOURCES.filter(
        (source) => loadedSourceTypes.has(source.sourceType),
    ).length
    const selected =
        REPORTING_SOURCES.find((source) => source.sourceType === selectedSourceType)
        ?? REPORTING_SOURCES[0]
    const selectedLoaded = loadedSourceTypes.has(selected.sourceType)
    const allLoaded = loadedCount === REPORTING_SOURCES.length

    return (
        <Box
            sx={{
                flex: 1,
                minHeight: 0,
                display: 'flex',
                flexDirection: 'column',
                p: { xs: 1, md: 1.5 },
                gap: 1,
            }}
        >
            <Box>
                <Stack direction="row" spacing={1} alignItems="baseline" flexWrap="wrap">
                    <Typography variant="subtitle1" fontWeight={800}>
                        Источники данных показателя 6.1.3.2.7
                    </Typography>
                    <Chip
                        size="small"
                        color={allLoaded ? 'success' : 'default'}
                        variant={allLoaded ? 'filled' : 'outlined'}
                        label={`Загружено ${loadedCount} из ${REPORTING_SOURCES.length} обязательных`}
                    />
                </Stack>
                <Typography variant="caption" color="text.secondary">
                    Порядок важен: справочник признаков МО (шаг 5) и ТПГГ (шаг 7) читаются
                    матрицей применимости (шаг 8) в момент подтверждения. Без любого из них
                    матрицу применить нельзя.
                    Выберите источник слева, чтобы увидеть подробности.
                </Typography>
            </Box>

            <Box
                sx={{
                    flex: 1,
                    minHeight: 0,
                    display: 'grid',
                    gridTemplateColumns: { xs: '1fr', md: 'minmax(250px, 32%) 1fr' },
                    gap: 1,
                }}
            >
                <Paper variant="outlined" sx={{ minHeight: 0, overflowY: 'auto', p: 0.5 }}>
                    <List dense disablePadding>
                        {REPORTING_SOURCES.map((source) => {
                            const loaded = loadedSourceTypes.has(source.sourceType)
                            return (
                                <ListItemButton
                                    key={source.sourceType}
                                    selected={source.sourceType === selected.sourceType}
                                    onClick={() => setSelectedSourceType(source.sourceType)}
                                    sx={{ borderRadius: 1, py: 0.55 }}
                                >
                                    <Box
                                        sx={{
                                            width: 22,
                                            height: 22,
                                            mr: 1,
                                            flexShrink: 0,
                                            borderRadius: '50%',
                                            display: 'grid',
                                            placeItems: 'center',
                                            fontWeight: 800,
                                            fontSize: 12,
                                            bgcolor: 'action.selected',
                                        }}
                                    >
                                        {source.step}
                                    </Box>
                                    <Box
                                        component="span"
                                        title={loaded ? 'Файл загружен' : 'Файл не загружен'}
                                        sx={{
                                            width: 9,
                                            height: 9,
                                            mr: 1,
                                            flexShrink: 0,
                                            borderRadius: '50%',
                                            bgcolor: loaded ? 'success.main' : 'error.main',
                                        }}
                                    />
                                    <ListItemText
                                        primary={source.title}
                                        primaryTypographyProps={{
                                            variant: 'body2',
                                            fontWeight: 700,
                                            noWrap: true,
                                        }}
                                    />
                                </ListItemButton>
                            )
                        })}
                    </List>
                </Paper>

                <Paper variant="outlined" sx={{ minHeight: 0, overflowY: 'auto', p: 1.5 }}>
                    <Stack direction="row" spacing={1} alignItems="center" flexWrap="wrap">
                        <Typography variant="subtitle2" fontWeight={800}>
                            Шаг {selected.step}. {selected.title}
                        </Typography>
                        <Chip
                            size="small"
                            color={selectedLoaded ? 'success' : 'default'}
                            variant={selectedLoaded ? 'filled' : 'outlined'}
                            label={selectedLoaded ? 'загружен' : 'не загружен'}
                        />
                    </Stack>
                    <ReferenceRow label="Что содержит" value={selected.contains} />
                    <ReferenceRow label="Ключевые поля" value={selected.keyFields} />
                    <ReferenceRow label="Роль в расчёте" value={selected.role} />
                    <ReferenceRow label="Если не загружен" value={selected.ifMissing} />
                    <ReferenceRow
                        label="Откуда брать"
                        value={
                            SHOW_DETAILED_SOURCE_ORIGIN
                                ? selected.originDetailed ?? selected.origin
                                : selected.origin
                        }
                        href={
                            SHOW_DETAILED_SOURCE_ORIGIN
                                ? selected.hrefDetailed ?? selected.href
                                : selected.href
                        }
                        hrefLabel={
                            SHOW_DETAILED_SOURCE_ORIGIN ? selected.hrefLabel : undefined
                        }
                    />
                </Paper>
            </Box>
        </Box>
    )
}

function ReferenceRow({
    label,
    value,
    href,
    hrefLabel,
}: {
    label: string
    value: string
    href?: string
    hrefLabel?: string
}) {
    return (
        <Typography variant="body2" sx={{ mt: 0.75, overflowWrap: 'anywhere' }}>
            <Box component="span" sx={{ color: 'text.secondary', fontWeight: 700 }}>
                {label}:{' '}
            </Box>
            {value}
            {href && (
                <>
                    {' '}
                    <Link href={href} target="_blank" rel="noopener noreferrer">
                        {hrefLabel ?? 'открыть справочник'}
                    </Link>
                </>
            )}
        </Typography>
    )
}
