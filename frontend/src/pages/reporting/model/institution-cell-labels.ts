export function getInstitutionCellLabel(
    institutionOid: string,
    institutionName: string,
): string {
    const configured = INSTITUTION_CELL_LABELS[institutionOid]
    if (configured) return configured

    const quoted = institutionName.match(/"([^"]+)"/)?.[1] ?? institutionName
    const compact = quoted
        .toLocaleUpperCase('ru-RU')
        .replace(/^(ГБУ|ГКУ|АО|МАУЗ)\s+/, '')
        .replace(/\s+/g, ' ')
        .trim()

    if (compact.length <= 10) return compact || 'МО'

    return compact
        .split(/\s+/)
        .filter(Boolean)
        .slice(0, 4)
        .map((word) => word[0])
        .join('')
        .slice(0, 8) || 'МО'
}

export function hasConfiguredInstitutionCellLabel(institutionOid: string): boolean {
    return Object.prototype.hasOwnProperty.call(INSTITUTION_CELL_LABELS, institutionOid)
}
