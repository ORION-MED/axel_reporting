import { describe, expect, it } from 'vitest'
import {
    PILOT_EPGU_REFERENCE_TYPES,
    pilotCoverageLabel,
    semdTypeCountLabel,
} from './reporting-helpers'

/**
 * Число видов СЭМД в подписях интерфейса. До 07.08.2026 оно было вписано в семь
 * мест текстом («35 видов по региону», «Расшифровка по 35 видам СЭМД»), и когда
 * справочники дали 36-й вид, подписи разошлись с расчётом прямо на демонстрации.
 * Тесты фиксируют оба правила: число берётся из расчёта, а до загрузки данных —
 * из состава справочника ЕПГУ (не из цели показателя — с 20.08.2026 она равна 35).
 */

describe('число видов СЭМД в подписи', () => {
    it('берёт число из расчёта, когда данные загружены', () => {
        expect(semdTypeCountLabel(36)).toBe(36)
    })

    it('показывает целевое значение, пока данных нет', () => {
        expect(semdTypeCountLabel(null)).toBe(PILOT_EPGU_REFERENCE_TYPES)
        expect(semdTypeCountLabel(undefined)).toBe(PILOT_EPGU_REFERENCE_TYPES)
    })

    it('пустой перечень — это «не загружено», а не «ноль видов»', () => {
        // «0 видов по региону» на кнопке означало бы, что справочник пуст,
        // хотя на деле период просто ещё не выбран.
        expect(semdTypeCountLabel(0)).toBe(PILOT_EPGU_REFERENCE_TYPES)
    })

    it('не подменяет число расчёта справочным, если они разошлись', () => {
        // Расхождение — это диагностика, а не повод показать «правильное» число:
        // в форме_1 может быть описано меньше видов, чем в справочнике ЕПГУ.
        expect(semdTypeCountLabel(35)).toBe(35)
    })

    it('число совпадает с backend PILOT_EPGU_REFERENCE_TYPES', () => {
        // Зеркало backend/src/reporting/pilot-calculation.types.ts — при расхождении
        // предпросмотр матрицы будет ругаться на состав справочника, а интерфейс молчать.
        expect(PILOT_EPGU_REFERENCE_TYPES).toBe(36)
    })

    it('в подписях про справочник стоит 36, а не цель показателя 35', () => {
        // С 20.08.2026 цель равна 35 (Соглашение, В-05), и это разные величины.
        // Подставить цель в подпись «36 из 36 видов» значило бы разойтись с окном
        // предпросмотра матрицы, которое блокирует применение при составе ≠ 36.
        expect(semdTypeCountLabel(null)).toBe(36)
    })
})

/**
 * Подпись под значением показателя 6.1.3.2.7.
 *
 * До 21.08.2026 она читалась «Исполнение 97,22 % · 35 / 36» и стояла рядом с чипом
 * «План выполнен» — выглядело как противоречие, и вопрос задавал каждый, кто
 * открывал карточку. На деле 35 — цель по Соглашению, она достигнута,
 * а 36 — состав справочника доступности на ЕПГУ.
 */
describe('pilotCoverageLabel', () => {
    it('называет доступность на ЕПГУ, а не исполнение', () => {
        expect(pilotCoverageLabel(35, 36)).toBe('Доступно на ЕПГУ: 35 из 36')
    })

    it('не содержит слова «исполнение» и процента', () => {
        // Процент убран сознательно: 97,22 % рядом с «План выполнен» и создавали
        // впечатление недовыполнения там, где цель достигнута.
        const label = pilotCoverageLabel(35, 36)

        expect(label).not.toContain('сполнение')
        expect(label).not.toContain('%')
    })

    it('пустое значение показывает прочерком, а не нулём', () => {
        // Ноль здесь означал бы «ни один вид не доступен», а не «данных нет».
        expect(pilotCoverageLabel(null, 36)).toBe('Доступно на ЕПГУ: — из 36')
        expect(pilotCoverageLabel(undefined, undefined)).toBe('Доступно на ЕПГУ: — из —')
    })
})
