/** Нормализация синонима — та же, что в миграциях: регистр, «ё» и края строки. */
export function normalizeOrganizationAlias(alias: string): string {
    // Порядок действий повторяет SQL миграций — lower(btrim(replace(alias, 'ё', 'е'))),
    // иначе одна и та же строка получит два разных ключа уникальности.
    return String(alias ?? '')
        .replace(/ё/g, 'е')
        .trim()
        .toLowerCase()
}

/**
 * Заводит рабочие синонимы для тех OID, что уже есть в реестре МО.
 * Возвращает число вставленных строк — в предупреждениях импорта оно не нужно,
 * но помогает в тестах и в журнале.
 */
export async function applyOrganizationAliasSeed(client: PoolClient): Promise<number> {
    let inserted = 0
    for (const entry of ORGANIZATION_ALIAS_SEED) {
        const result = await client.query(
            `
            INSERT INTO reporting_organization_aliases (
                organization_oid,
                alias,
                normalized_alias,
                alias_kind
            )
            SELECT organization.oid, $2, $3, $4
            FROM reporting_organizations organization
            WHERE organization.oid = $1
            ON CONFLICT (organization_oid, normalized_alias) DO NOTHING;
            `,
            [entry.oid, entry.alias, normalizeOrganizationAlias(entry.alias), entry.kind],
        )
        inserted += result.rowCount ?? 0
    }
    return inserted
}
