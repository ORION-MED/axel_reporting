import { toDateString } from './reporting-format.util'

/**
 * Отчётная дата периода. Драйвер `pg` отдаёт колонку `DATE` как локальную полночь,
 * и прежняя реализация переводила её в UTC — восточнее Гринвича дата уезжала
 * на день назад. От неё зависят выбор действующей редакции справочника видов СЭМД
 * и месяц накопительного плана ТПГГ, то есть ошибка меняет расчёт молча.
 *
 * Тесты сформулированы через локальные компоненты, а не через литерал в UTC:
 * иначе на машине в UTC (как контейнер стенда) они прошли бы и на сломанном коде.
 */
describe('toDateString', () => {
    it('сохраняет календарную дату, прочитанную драйвером', () => {
        // Ровно то, что делает pg с колонкой DATE '2026-08-31'.
        expect(toDateString(new Date(2026, 7, 31))).toBe('2026-08-31')
    })

    it('не зависит от часового пояса машины', () => {
        // Инвариант, верный в любой зоне: результат совпадает с локальными
        // компонентами даты. Именно его нарушал toISOString().
        const value = new Date(2026, 7, 31)
        const expected = [
            value.getFullYear(),
            String(value.getMonth() + 1).padStart(2, '0'),
            String(value.getDate()).padStart(2, '0'),
        ].join('-')

        expect(toDateString(value)).toBe(expected)
    })

    it('последний день года не превращается в предыдущий', () => {
        // Самый дорогой случай: сдвиг на день назад менял бы и год, а вместе с ним
        // и редакцию справочника, действующую на отчётную дату.
        expect(toDateString(new Date(2026, 11, 31))).toBe('2026-12-31')
    })

    it('первый день месяца не уезжает в предыдущий месяц', () => {
        // Для показателей-долей это сменило бы месяц накопительного плана ТПГГ.
        expect(toDateString(new Date(2026, 8, 1))).toBe('2026-09-01')
    })

    it('однозначные месяц и день дополняются нулём', () => {
        expect(toDateString(new Date(2026, 0, 5))).toBe('2026-01-05')
    })

    it('строку из SQL-каста ::text отдаёт как есть', () => {
        // Часть запросов кастует дату в текст — там сдвига не было и быть не может.
        expect(toDateString('2026-08-31')).toBe('2026-08-31')
        expect(toDateString('2026-08-31T00:00:00.000Z')).toBe('2026-08-31')
    })

    it('пустое значение — это отсутствие даты, а не сегодняшняя', () => {
        expect(toDateString(null)).toBeNull()
        expect(toDateString(undefined)).toBeNull()
        expect(toDateString('')).toBeNull()
    })
})
