import { splitGroundText } from './applicability-matrix-xlsx'

/**
 * Замечание от 29.07: в колонке «Основание» расшифровки МО показывались личные рабочие
 * заметки методолога («я не нашла такого по Курганской области»). По ТЗ 24.07 экспертность
 * системы строится на нормах, а не на комментариях живого эксперта, поэтому нормативная
 * формулировка и рабочая заметка разделяются при импорте формы_1.
 */
describe('splitGroundText', () => {
    it('отделяет личную заметку методолога от нормативной формулировки', () => {
        const result = splitGroundText(
            'реализация гос.программ по обеспечению населения ЛЛО. '
            + 'В идеале должен быть региональный приказ, я не нашла такого по Курганской области. '
            + 'Пока что включаем все МО с прикрепленным населением.',
        )

        expect(result.text).toBe('реализация гос.программ по обеспечению населения ЛЛО.')
        expect(result.workingNote).toContain('я не нашла')
        expect(result.workingNote).toContain('Пока что включаем')
    })

    it('не трогает чистые нормативные формулировки', () => {
        const texts = [
            'наличие объема МП, утвержденного государственным заданием региона',
            'при наличии лицензии на вид мед.деятельности 1080.1. медицинским осмотрам (предварительным, периодическим)',
            'наличие прикрепленного детского населения',
            'оказание стационарной МП или в условиях дневного стационара',
        ]

        for (const text of texts) {
            const result = splitGroundText(text)
            expect(result.text).toBe(text)
            expect(result.workingNote).toBe('')
        }
    })

    it('сохраняет многофразную норму без маркеров целиком', () => {
        const result = splitGroundText(
            'условия входимости ТВСП МО в показатель. Слайд 12 методики.',
        )

        expect(result.text).toBe('условия входимости ТВСП МО в показатель. Слайд 12 методики.')
        expect(result.workingNote).toBe('')
    })

    it('никогда не оставляет основание пустым: берёт первую фразу', () => {
        const result = splitGroundText(
            'Я думаю, это нужно уточнить. Возможно, стоит спросить регион.',
        )

        expect(result.text).toBe('Я думаю, это нужно уточнить.')
        expect(result.workingNote).toBe('Возможно, стоит спросить регион.')
    })

    it('вопросительная фраза считается рабочей заметкой', () => {
        const result = splitGroundText(
            'оказание МП по заболеваниям, подлежащим МСЭ. Уточнить перечень?',
        )

        expect(result.text).toBe('оказание МП по заболеваниям, подлежащим МСЭ.')
        expect(result.workingNote).toBe('Уточнить перечень?')
    })

    it('пустая ячейка остаётся пустой', () => {
        expect(splitGroundText('   ')).toEqual({ text: '', workingNote: '' })
    })
})
