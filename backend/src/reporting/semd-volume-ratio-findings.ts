import type { SemdVolumeRatioResult } from './semd-volume-ratio.calculator'

/**
 * Н20 (ВКС 15.08.2026, 00:20:12): у части МО зарегистрировано документов больше,
 * чем случаев в накопительном плане. Методолог знает причину и просит показывать её
 * «тем же выпадающим меню, как Илья делал на самый первый показатель» — то есть
 * механизмом находок, а не отдельным экраном.
 *
 * Находка — надстройка над готовым результатом расчёта: числитель, знаменатель
 * и процент она не трогает. Это важно, потому что перевыполнение здесь не ошибка
 * данных: по словам методолога в КЦМП комплексное исследование оформляется
 * двенадцатью случаями вместо одного, и двенадцать эпикризов — норма учёта,
 * а не дубли.
 */
export const VOLUME_RATIO_OVERACHIEVED_CODE = 'volume_ratio_plan_overachieved'

export interface SemdVolumeRatioFinding {
    organizationOid: string
    findingCode: string
    severity: 'info' | 'warning' | 'error'
    cause: string
    responsibilityArea: string
    recommendation: string
    evidence: Record<string, unknown>
}

/**
 * Формулировка методолога, ответ на вопрос В-03 из файла согласования от 20.08.2026
 * («Решено», причина № 20 листа действующих правил).
 *
 * До 20.08.2026 здесь стоял временный текст, который описывал факт и прямо говорил,
 * что причина уточняется. Ждали ответа на развилку «причина одна или у каждой МО
 * своя»: предполагалось, что у КЦМП это дробление комплексного исследования,
 * а у инфекционной больницы и КОКВД — что-то другое. Методолог ответила, что
 * **причина общая и перевыполнение возможно у любой МО**, поэтому текст один
 * на всех — как того и требует группировка окна причин.
 *
 * Две составляющие перевыполнения по её ответу: декабрьский хвост, который
 * регистрируется в РЭМД в течение следующего года, и некорректное оформление
 * случаев амбулаторной помощи. Первая — про сроки отправки, вторая — про дробление;
 * отсюда обе части рекомендации.
 */
const OVERACHIEVED_CAUSE = 'Зарегистрировано больше документов, чем случаев оказания '
    + 'помощи в накопительном плане. Превышение возникает регулярно: в декабре на '
    + 'регистрацию в РЭМД скапливается большое количество документов, которые '
    + 'регистрируются в течение следующего года, а часть МО некорректно оформляет '
    + 'случаи амбулаторной помощи. Превышение возможно у любой МО.'
const OVERACHIEVED_RECOMMENDATION = 'Проанализировать оформление амбулаторных случаев '
    + 'в ГИС на предмет дробления комплексных медицинских осмотров и случаев '
    + 'заболевания, привести его в соответствие с положениями Территориальной '
    + 'программы ОМС. Контролировать своевременность отправки СЭМД на регистрацию '
    + 'в РЭМД — не оставлять отправку на конец недели, месяца или года.'

/**
 * Зона ответственности — МО: оба действия рекомендации выполняются в самой
 * медицинской организации (оформление случаев в ГИС и своевременная отправка).
 * До 20.08.2026 стояла «МИАЦ / аналитик предметной области», потому что находка
 * ждала объяснения от методолога, а не действия от больницы.
 */
const RESPONSIBILITY_AREA = 'МО'

/**
 * Находки по показателю-доле. Сейчас код один — перевыполнение накопительного плана;
 * функция возвращает массив, потому что следующие коды лягут сюда же.
 */
export function buildVolumeRatioFindings(
    result: SemdVolumeRatioResult,
): SemdVolumeRatioFinding[] {
    const findings: SemdVolumeRatioFinding[] = []
    for (const organization of result.organizations) {
        // Процент есть только у МО с утверждённым и расписанным объёмом. У остальных
        // перевыполнения не существует — не «оно нулевое», а сравнивать не с чем.
        if (organization.status !== 'calculated') continue
        if (organization.percent === null || organization.denominator === null) continue
        if (organization.percent <= 100) continue

        const excessDocuments = organization.numerator - organization.denominator
        findings.push({
            organizationOid: organization.organizationOid,
            findingCode: VOLUME_RATIO_OVERACHIEVED_CODE,
            // Не ошибка и не предупреждение: план перевыполнен, а не нарушен.
            severity: 'info',
            // Текст один на всех, цифры — в основании. Окно причин группирует находки
            // по тексту («одна причина — один раз, со списком затронутых МО», FR-11),
            // и подстановка чисел разбила бы девять находок на девять одинаковых
            // абзацев. Ровно поэтому у 6.1.3.2.7 есть пара «с названием / без».
            cause: OVERACHIEVED_CAUSE,
            responsibilityArea: RESPONSIBILITY_AREA,
            recommendation: OVERACHIEVED_RECOMMENDATION,
            evidence: {
                numerator: organization.numerator,
                denominator: organization.denominator,
                percent: organization.percent,
                excessDocuments,
            },
        })
    }
    return findings
}

