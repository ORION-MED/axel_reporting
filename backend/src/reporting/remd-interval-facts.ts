import type { RemdReportInterval } from './remd-numerator-xlsx'

/**
 * Разновидности выгрузок РЭМД за интервал и правило, по которому одна отличается
 * от другой.
 *
 * Методолог 25.08.2026 прислала тринадцать отчётов за один и тот же отчётный
 * период — семь помесячных и шесть нарастающим итогом — и провела границу
 * по назначению: «для показателя 27 по региону и по МО количество уникальных
 * СЭМД берём из выгрузки нарастающим итогом, а динамика по кол-ву СЭМД —
 * с каждого месяца».
 *
 * Значит, сервису нужно знать про каждый файл, какой он. Единственный надёжный
 * признак — интервал в шапке самого отчёта. Имя файла не годится: «7.Отчет
 * СЭМД_РЭМД июль» и «7.Отчет СЭМД_РЭМД янв-июль» начинаются одинаково, и
 * перепутать их значит смешать 1 236 272 документа июля с 6 785 824 за семь
 * месяцев на одном графике.
 */

export type RemdIntervalCoverage = 'month' | 'cumulative'

export interface RemdIntervalTag {
    coverage: RemdIntervalCoverage
    /** Месяц выгрузки; у нарастающей — последний месяц интервала. */
    month: number
    year: number
}

/**
 * Пометка выгрузки по её интервалу. `null` означает «сами не решаем» — месяц
 * и разновидность спрашиваются у пользователя в предпросмотре.
 *
 * Отказ молчаливо угадывать здесь важнее удобства: неверно помеченный файл
 * не ломает импорт и не выдаёт ошибку, он просто рисует неверную кривую,
 * и заметить это можно только пересчитав всё вручную.
 */
export function classifyRemdInterval(
    interval: RemdReportInterval | null,
): RemdIntervalTag | null {
    if (!interval) return null
    const { from, to } = interval
    // Выгрузка на стыке лет не бывает ни месяцем, ни «нарастающим с января»:
    // накопительный итог считается внутри года, как и план ТПГГ.
    if (from.year !== to.year) return null
    // Интервал, начатый не с первого числа, — это часть месяца. Для кривой
    // такая точка занижена, и подставлять её молча нельзя.
    if (from.day !== 1) return null
    if (to.month < from.month) return null
    if (from.month === to.month) {
        // Январь один — это одновременно и месяц, и «нарастающий по январь»;
        // числа в них совпадают. Считаем месяцем: у графика точка появится,
        // а показателю 27 нарастающая за один январь всё равно не нужна.
        return { coverage: 'month', month: to.month, year: to.year }
    }
    if (from.month === 1) {
        return { coverage: 'cumulative', month: to.month, year: to.year }
    }
    // Произвольный интервал вроде «март-июнь»: ни месяц, ни нарастающий итог.
    return null
}

/**
 * Из нескольких нарастающих выгрузок показателю 27 нужна одна — самая полная.
 * Методолог прислала шесть, от «янв-фев» до «янв-июль»; числитель берётся
 * из последней, остальные остаются историей.
 */
export function latestCumulativeMonth(
    months: readonly number[],
): number | null {
    let latest: number | null = null
    for (const month of months) {
        if (latest === null || month > latest) latest = month
    }
    return latest
}
