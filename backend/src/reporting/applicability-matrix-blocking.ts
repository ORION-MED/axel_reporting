/**
 * Что запрещает применить матрицу применимости.
 *
 * Правила собраны в одну чистую функцию сознательно: раньше они лежали внутри
 * `buildPreview` вперемешку с подсчётами, и проверить их можно было только поднимая
 * базу целиком. Здесь на вход подаются готовые числа — это и есть правило проекта
 * «тесты на чистую логику обязательны».
 *
 * Разница между предупреждением и блокировкой: предупреждение методолог читает и решает
 * сам, блокировка означает, что применённая матрица дала бы неверный расчёт молча.
 */

export interface MatrixBlockingInput {
    /** Сколько МО в справочнике; пусто — числитель РЭМД ещё не загружен. */
    organizationCount: number
    /** Сколько видов СЭМД доступно гражданам на ЕПГУ на отчётную дату. */
    epguTypeCount: number
    /** Ожидаемый состав справочника ЕПГУ (`PILOT_EPGU_REFERENCE_TYPES`), не цель показателя. */
    expectedEpguTypeCount: number
    /** Коды формы, которых нет в справочнике видов СЭМД вообще, — опечатки. */
    unknownSemdTypeCodes: readonly string[]
    /** ЕПГУ-коды, для которых в форме не нашлось ни одного правила. */
    missingMatrixSemdTypeCodes: readonly string[]
    /** Загружен ли справочник признаков МО (шаг 5). */
    directoryLoaded: boolean
    /** Имена из условий «если МО НЕ …», которые не нашлись в справочнике МО. */
    unmatchedExclusionOrganizationNames: readonly string[]
}

export interface OrphanedInclusionList {
    /** Наименование из формы, как его написал методолог: «Санаторий», «Диспансер». */
    organizationName: string
    /** Коды видов СЭМД, чьи правила ссылаются на это наименование. */
    semdTypeCodes: readonly string[]
}

/**
 * Справочник признаков МО обязателен с 07.08.2026 (требование методолога, шестое сообщение
 * ТЗ: «Признак наличия прикреплённого населения необходимо сделать обязательным»).
 *
 * Причина именно в блокировке, а не в предупреждении: без справочника перечни МО для условий
 * «прикреплённое население» и «при наличии лицензии…» собираются разбором текста из колонки
 * «Комментарий методолога». Разбор завязан на курганские сокращения наименований и даёт
 * другой состав — на данных Курганской области 24 пары «МО × вид СЭМД» из 1 295. Ошибка
 * при этом не видна: расчёт проходит, проценты выглядят правдоподобно.
 *
 * Цена решения: новый регион не сможет применить матрицу, пока не заполнит справочник.
 * Это ровно то, чего хочет методолог.
 */
export const ORGANIZATION_DIRECTORY_IS_REQUIRED = true

export function buildMatrixBlockingErrors(input: MatrixBlockingInput): string[] {
    const errors: string[] = []

    if (input.organizationCount === 0) {
        errors.push(
            'Справочник МО пуст. Сначала загрузите числитель РЭМД: он создаст 37 целевых МО.',
        )
    }
    if (input.epguTypeCount !== input.expectedEpguTypeCount) {
        errors.push(
            `В справочнике ЕПГУ найдено ${input.epguTypeCount} видов СЭМД `
            + `вместо ${input.expectedEpguTypeCount}.`,
        )
    }
    // Блокирует только неизвестный код: он означает опечатку, и молча пропустить
    // такую строку нельзя. Вид, известный справочнику, но недоступный на ЕПГУ,
    // применению матрицы не мешает — он просто вне показателя 6.1.3.2.7.
    if (input.unknownSemdTypeCodes.length > 0) {
        errors.push(
            `Кодов нет в справочнике видов СЭМД: ${input.unknownSemdTypeCodes.join(', ')}.`,
        )
    }
    if (input.missingMatrixSemdTypeCodes.length > 0) {
        errors.push(
            `В матрице нет правил для ЕПГУ-кодов: ${input.missingMatrixSemdTypeCodes.join(', ')}.`,
        )
    }
    // Несопоставленное имя в обычном перечне — предупреждение: правило сузится, и это
    // видно по цифрам предпросмотра. В перечне-исключении наоборот: МО останется
    // обязанной, состав не изменится, и правка методолога тихо не сработает.
    // Проверить это глазами нельзя — потому блокировка.
    if (input.unmatchedExclusionOrganizationNames.length > 0) {
        errors.push(
            'В условиях «если МО НЕ …» не сопоставлены наименования: '
            + `${input.unmatchedExclusionOrganizationNames.join(', ')}. `
            + 'Эти МО останутся обязанными, хотя форма их исключает. '
            + 'Добавьте синоним в справочник МО или поправьте наименование в форме.',
        )
    }
    // Перечня-включения без адресата здесь намеренно нет. До 25.08.2026 он блокировал
    // импорт: правило, адресованное никому, молча превращало вид в «не обязателен
    // всем» — у ГКУ «КОБСМЭ» из шести правил «если МО - Бюро СМЭ» выходило ноль
    // обязательных видов, по цифрам неотличимо от честного нуля. Неверный исход убран
    // в самом расчёте (`evaluateRule` возвращает «не определено»), и запрещать из-за
    // трёх видов загрузку всех ста сорока пяти стало нечем оправдать. Теперь это
    // предупреждение — `buildMatrixOrphanedInclusionWarning`.
    if (ORGANIZATION_DIRECTORY_IS_REQUIRED && !input.directoryLoaded) {
        errors.push(
            'Не загружен справочник признаков МО (шаг 5). Загрузите его до матрицы: '
            + 'из него берутся перечни МО для условий «прикреплённое население» '
            + 'и «при наличии лицензии…». Без справочника эти перечни собираются разбором '
            + 'комментариев формы_1 и дают неверный состав обязательных видов.',
        )
    }

    return errors
}

/**
 * Предупреждение о перечнях-включениях без адресата: вид останется «не определено»
 * у всех МО, расчёт по ним будет предварительным. Импорт при этом проходит —
 * остальные правила формы применяются как есть.
 *
 * Возвращает пустую строку, когда таких перечней нет: вызывающему удобнее
 * проверить `length`, чем городить условие вокруг вызова.
 */
export function buildMatrixOrphanedInclusionWarning(
    orphanedInclusionLists: readonly OrphanedInclusionList[],
): string {
    if (orphanedInclusionLists.length === 0) return ''
    const listed = orphanedInclusionLists
        .map((item) => `${item.organizationName} (виды ${item.semdTypeCodes.join(', ')})`)
        .join('; ')
    return (
        'Перечни МО не нашли ни одной организации: '
        + `${listed}. Эти виды останутся «не определено» у всех МО, `
        + 'и расчёт по ним будет предварительным. Назовите организацию '
        + 'или поставьте виду «не обязателен».'
    )
}
